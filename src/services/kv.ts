// SecureStore on native, localStorage on web; values above SecureStore's size limit are refused, not truncated.

import { Platform } from "react-native";
import * as SecureStore from "expo-secure-store";

export const kv = {
  async get(key: string): Promise<string | null> {
    if (Platform.OS === "web") {
      try {
        return globalThis.localStorage?.getItem(key) ?? null;
      } catch {
        return null;
      }
    }
    return SecureStore.getItemAsync(key);
  },
  async set(key: string, value: string): Promise<void> {
    if (Platform.OS === "web") {
      try {
        globalThis.localStorage?.setItem(key, value);
      } catch {
        // Best-effort: a blocked or full store must not fail the caller.
      }
      return;
    }
    await SecureStore.setItemAsync(key, value);
  },
  async remove(key: string): Promise<void> {
    if (Platform.OS === "web") {
      try {
        globalThis.localStorage?.removeItem(key);
      } catch {
        // Symmetric with `set`: a store that cannot be written cannot be
        // cleared either, and a sign-out must not be the thing that fails.
      }
      return;
    }
    await SecureStore.deleteItemAsync(key);
  },
};
